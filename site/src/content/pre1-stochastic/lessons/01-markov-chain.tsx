      <Section title="よくある勘違い">
        <Pitfall>
          <ul>
            <li>
              推移確率行列の<strong>列</strong>の和が 1 だと思う → このサイト（と多くの統計の本）の書き方では、行が「いま」、列が「次」なので、<strong>行</strong>の和が 1。
              本によっては転置した（列の和が 1 の）書き方もあるので、問題文の定義を確認する。
            </li>
            <li>
              分布に行列を<strong>左から</strong>かける → 横ベクトルの分布には右から <M>{'P'}</M> をかける（<M>{'\\boldsymbol{\\mu} P'}</M>）。
            </li>
            <li>
              「定常分布になると、状態が動かなくなる」→ 動かなくなるのは<strong>確率</strong>。状態そのものは毎ステップ移り変わっている。
            </li>
            <li>
              「定常分布があれば、必ずそこに近づく」→ 周期があると近づかない（周期 2 の例）。近づくことが保証されるのは、有限・既約・非周期のとき。
            </li>
            <li>
              <M>{'\\boldsymbol{\\pi} P = \\boldsymbol{\\pi}'}</M> の式だけで解こうとして解が1つに決まらない → 「足して 1」の式を必ず加える。
            </li>
          </ul>
        </Pitfall>
      </Section>

