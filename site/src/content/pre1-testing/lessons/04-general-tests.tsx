        <p>
          <Link to="/lessons/testing-chi2">2級の適合度検定</Link>では、サイコロの目のように理論の確率が<strong>最初から決まっている</strong>ものを扱い、自由度は「カテゴリーの数 − 1」でした。
          でも「このデータはポアソン分布にしたがうか」のように、λ を<strong>データから推定してから</strong>期待度数を作ることがよくあります。
        </p>
