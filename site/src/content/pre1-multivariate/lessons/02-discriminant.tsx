      <Section title="よくある勘違い">
        <Pitfall>
          <ul>
            <li>判別関数の重みを平均の差 <M>{'\\bar{\\boldsymbol{x}}_B - \\bar{\\boldsymbol{x}}_A'}</M> そのものにする → <M>{'S^{-1}'}</M> をかけ忘れている。変数に相関があると向きが変わる。</li>
            <li>感度と適合率を取り違える → 感度は「病気の人のうち陽性」、適合率は「陽性の人のうち病気」。分母が違う。</li>
            <li>AUC = 0.5 は「半分当たるのでまあまあ」 → AUC 0.5 はでたらめに判定するのと同じ。AUC が 0.5 未満なら、判定を逆にしたほうがよい。</li>
            <li>ROC 曲線の横軸を特異度にする → 横軸は偽陽性率（1 − 特異度）。</li>
            <li>学習に使ったデータで正解率を計算して「よく当たる」と判断する → 同じデータでは楽観的に出る。新しいデータ（検証用データ）や交差検証で評価する。</li>
          </ul>
        </Pitfall>
      </Section>

