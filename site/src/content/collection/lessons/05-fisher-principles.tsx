import { Example, ExamTip, Figure, Intuition, Pitfall, Point, Section } from '../../../components/blocks'
import type { LessonMeta } from '../../../types'
import { TextTable } from '../figures/TextTable'
import { FieldExperiment } from '../figures/FieldExperiment'

export const meta: LessonMeta = {
  id: 'collection-fisher-principles',
  chapter: 'collection',
  order: 5,
  title: '実験計画とフィッシャーの3原則',
  summary: '実験で処理の効果を正しく比べるための3つの原則（反復・無作為化・局所管理）と、処理群・対照群、プラセボ・二重盲検を学びます。',
  minutes: 25,
  keywords: ['実験のデザイン（実験計画）', 'フィッシャーの3原則', '反復', '無作為化', '局所管理（ブロック化）', '処理群', '対照群'],
}

export default function Lesson() {
  return (
    <>
      <Point>
        <p>
          実験の結果から処理の効果を正しく読みとるには、<strong>フィッシャーの3原則</strong>を守ります。
          <strong>反復</strong>（同じ処理を何回もくり返す）、<strong>無作為化</strong>（どこに・誰に何の処理をするかをくじで決める）、
          <strong>局所管理</strong>（条件の似たものをまとめたブロックの中で比べる）の3つです。
        </p>
      </Point>

      <Section title="実験計画とは">
        <p>
          実験研究では、調べる側が処理を割り当てます。<strong>どの処理を、どこに、いくつ割り当てるか</strong>を前もって決めることを
          <strong>実験計画</strong>（実験のデザイン）といいます。統計学者フィッシャーが、農業試験場で肥料や品種を比べる実験から整理した考え方です。
        </p>
        <p>
          新しい処理を受けるグループを<strong>処理群</strong>（実験群）、比べるための基準になる、新しい処理を受けないグループを<strong>対照群</strong>（コントロール群）といいます。
          効果は「処理群と対照群の差」で測ります。
        </p>
      </Section>

      <Section title="畑の実験で3原則を見てみよう">
        <p>
          新しい肥料A が、今までの肥料B より収量（とれる量）を増やすかを、16区画の畑で調べます。この畑は<strong>左ほど土が肥えていて</strong>、
          肥料に関係なく左の区画ほどよくとれます。本当の効果は「A は B より +2」とします。①から④へ順に切り替えてみてください。
        </p>
        <Figure caption="区画の緑の濃さが土の肥え具合。青枠が肥料A、オレンジ枠が肥料B。下の表は、同じ配置で実験を2000回やり直したシミュレーションの結果">
          <FieldExperiment />
        </Figure>
        <TextTable
          head={['原則', 'すること', 'ねらい']}
          rows={[
            ['反復', '同じ処理を複数の区画（人）で行う', 'たまたまのぶれ（誤差）の大きさがわかり、差がぶれより大きいかを判断できる。くり返すほど推定のぶれが小さくなる'],
            ['無作為化', 'どの区画にどの処理をするかを、くじで決める', '土の質のような、気づいていない要因によるかたよりを防ぐ（偏りをなくす）'],
            ['局所管理（ブロック化）', '条件の似た区画をまとめてブロックにし、ブロックの中で処理を比べる', 'ブロックどうしの条件のちがい（土の質）を差から取り除き、精度を上げる'],
          ]}
        />
        <Intuition title="図の表から読みとれること">
          <ul>
            <li>①と②は推定値の平均が +2 から大きくずれている：土のちがいが効果にまざっている（<strong>偏り</strong>）。反復だけでは直らない。</li>
            <li>③は平均がほぼ +2：無作為化で偏りが消えた。ただし、くじしだいで土のかたよりが起きるので、ばらつきは大きめ。</li>
            <li>④は平均がほぼ +2 で、ばらつきも③より小さい：局所管理で土のちがいを打ち消したので、<strong>精度</strong>がよくなった。</li>
          </ul>
        </Intuition>
        <p>
          ④のように、ブロックを作り、各ブロックの中で処理をくじで割り当てる計画を<strong>乱塊法</strong>（乱塊法実験）といいます。
          どれだけ差があれば「効果あり」と言えるかを調べる分散分析は、「線形モデル」の章で扱います。
        </p>
      </Section>

      <Section title="人を対象にした実験：プラセボと二重盲検">
        <p>
          薬の実験では、「薬を飲んだ」という思い込みだけで体調がよくなることがあります（<strong>プラセボ効果</strong>）。
          そこで対照群には、見た目は同じで有効成分の入っていない<strong>プラセボ</strong>（偽薬）を飲んでもらい、思い込みの影響をそろえます。
        </p>
        <p>
          さらに、患者だけでなく、薬を渡したり効果を判定したりする医師も、誰が本物の薬を飲んでいるかを知らないようにする方法を<strong>二重盲検法</strong>といいます。
          医師の期待が、接し方や判定にまざるのを防ぐためです。
        </p>
        <Example title="新しい勉強アプリの効果を調べる実験">
          <ul>
            <li>くじで生徒を2つの群に分ける（無作為化）。片方は新しいアプリ（処理群）、もう片方は今までの教材（対照群）。</li>
            <li>各群に30人ずつ入れる（反復）。1人ずつでは、たまたまの差と区別できない。</li>
            <li>もともとの成績で「上位・中位・下位」のブロックに分け、ブロックの中でくじを引く（局所管理）。</li>
          </ul>
        </Example>
      </Section>

      <Section title="よくある勘違い">
        <Pitfall>
          <ul>
            <li>反復 = 同じ区画を何回も測り直すこと → 反復は<strong>処理を複数の実験単位（区画・人）に行う</strong>こと。同じ区画の測り直しでは、区画ごとのぶれがわかりません。</li>
            <li>くじで割り当てれば、ブロックは不要 → 無作為化で偏りは防げますが、ぶれは残ります。わかっている大きな要因はブロック化すると精度が上がります。</li>
            <li>局所管理と層化抽出法の混同 → 似た考え方ですが、局所管理は<strong>実験で処理を割り当てる</strong>とき、層化抽出法は<strong>調査で標本を選ぶ</strong>ときの工夫です。</li>
            <li>対照群は「何もしない群」でなければならない → プラセボや今までの方法（標準的な処理）を対照にすることも多いです。</li>
          </ul>
        </Pitfall>
      </Section>

      <Section title="統計検定での出方">
        <ExamTip>
          <ul>
            <li>実験の手順の説明を読み、反復・無作為化・局所管理のどれにあたるかを選ぶ問題。</li>
            <li>うまくいかない実験の例を読み、どの原則が守られていないかを選ぶ問題。</li>
            <li>処理群・対照群、プラセボ、二重盲検の意味を問う問題。</li>
          </ul>
        </ExamTip>
      </Section>
    </>
  )
}
