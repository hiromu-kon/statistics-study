import { DataTable, Example, ExamTip, Figure, Intuition, MathNote, Pitfall, Point, Section, Steps } from '../../../components/blocks'
import { M, MathBlock } from '../../../components/Math'
import type { LessonMeta } from '../../../types'
import { GrowthTrap, IndexChart, SalesGrowthBars } from '../figures/GrowthFigures'

export const meta: LessonMeta = {
  id: 'collection-growth-rate',
  chapter: 'collection',
  order: 1,
  title: '成長率・幾何平均・指数化',
  summary: '「前の年より何%増えたか」を表す成長率と、その平均の正しいとり方（幾何平均）、基準の年を100にそろえる指数化を学びます。',
  minutes: 25,
  keywords: ['成長率', '幾何平均', '指数化', '基準時点'],
}

const YEARS = [2020, 2021, 2022, 2023, 2024]
const SALES = [200, 240, 264, 211.2, 253.44]

export default function Lesson() {
  return (
    <>
      <Point>
        <p>
          <strong>成長率</strong>は「前の時点より何%増えたか（減ったか）」。成長率の平均は、ふつうの平均（算術平均）ではなく、
          <strong>「何倍になったか」を掛け算して、回数ぶんのルートをとる（幾何平均）</strong>のが正しいとり方です。
          <strong>指数化</strong>は、ある時点（基準時点）の値を100にそろえて、伸び方を比べやすくする方法です。
        </p>
      </Point>

      <Section title="成長率：前の年より何%増えた？">
        <p>ある店の売上（万円）を5年分ならべ、各年の成長率を棒の上に書きました。</p>
        <Figure caption="棒が売上、上の数字が前の年からの成長率（緑は増加、赤は減少）">
          <SalesGrowthBars years={YEARS} values={SALES} />
        </Figure>
        <p>
          たとえば 2020年 → 2021年は 200万円 → 240万円。増えた分 40万円を<strong>前の年</strong>の 200万円で割って、
          <M>{'40 \\div 200 = 0.2'}</M>、つまり <strong>+20%</strong> です。
        </p>
        <p>
          時点 <M>{'t'}</M> の値を <M>{'x_t'}</M>、1つ前の時点の値を <M>{'x_{t-1}'}</M> と書くと、成長率 <M>{'r_t'}</M> は次の式です。
        </p>
        <MathBlock caption="成長率：前の時点と比べて、何割増えたか（増えた分 ÷ 前の時点の値）">{'r_t = \\frac{x_t - x_{t-1}}{x_{t-1}} = \\frac{x_t}{x_{t-1}} - 1'}</MathBlock>
        <p>
          右側の形 <M>{'x_t / x_{t-1}'}</M> は「何倍になったか」で、<strong>前年比</strong>とも呼ばれます。
          「前年比 120%」と「成長率 +20%」は同じことを言っています。この「何倍になったか」が、平均を考えるときの主役になります。
        </p>
        <DataTable
          head={['年', '売上（万円）', '前年比（何倍）', '成長率']}
          rows={[
            ['2020', '200', '—', '—'],
            ['2021', '240', '1.2', '+20%'],
            ['2022', '264', '1.1', '+10%'],
            ['2023', '211.2', '0.8', '−20%'],
            ['2024', '253.44', '1.2', '+20%'],
          ]}
          caption="売上と成長率"
        />
      </Section>

      <Section title="成長率を「ふつうに平均」すると間違う">
        <p>
          株価が1年目に <strong>+50%</strong>、2年目に <strong>−50%</strong> になったとします。2つの成長率をふつうに平均すると
          <M>{'(50 - 50) \\div 2 = 0'}</M>%。「平均すると変わらない」ように見えます。
        </p>
        <p>
          でも実際は、100円 → 150円 → <strong>75円</strong>。2年目の −50% は「150円の半分」なので、元の100円より下がってしまいます。
          スライダーで上がり下がりの幅を変えてみてください。
        </p>
        <Figure caption="同じ率だけ上がって下がると、元には戻らない。幅が大きいほど、算術平均と実際のずれが大きくなる">
          <GrowthTrap />
        </Figure>
        <Intuition title="なぜ足し算の平均ではだめなの？">
          <p>
            成長率は、<strong>毎年ちがう「もとの値」に対する割合</strong>です。+50% は100円の50%（50円）ですが、−50% は150円の50%（75円）。
            基準がちがう割合どうしを足しても意味がありません。毎年の変化は「足し算」ではなく「<strong>掛け算</strong>」で積み重なる
            （<M>{'100 \\times 1.5 \\times 0.5 = 75'}</M>）ので、平均も掛け算でとります。
          </p>
        </Intuition>
      </Section>

      <Section title="幾何平均：掛け算の平均">
        <p>
          「毎年同じ率で成長したとしたら、何%ずつなら同じ結果になるか」を考えます。2年で 1.5倍 × 0.5倍 = 0.75倍 になったので、
          毎年 <M>{'g'}</M> 倍とすると <M>{'g \\times g = 0.75'}</M>。つまり <M>{'g = \\sqrt{0.75} \\approx 0.866'}</M>。
          毎年およそ <strong>−13.4%</strong> ずつ減ったのと同じです（<M>{'100 \\times 0.866 \\times 0.866 \\approx 75'}</M>）。
        </p>
        <MathBlock caption="幾何平均 G：n 個の正の数を全部掛けて、n 乗根（n 回掛けるとその数になる数）をとる">{'G = \\sqrt[n]{x_1 \\times x_2 \\times \\cdots \\times x_n}'}</MathBlock>
        <MathBlock caption="平均成長率：各年の「何倍」（1 + 成長率）の幾何平均から 1 を引く">{'\\bar{r} = \\sqrt[n]{(1+r_1)(1+r_2)\\cdots(1+r_n)} - 1'}</MathBlock>
        <Example title="上の店の売上で計算すると">
          <Steps>
            <li>各年の「何倍」：1.2, 1.1, 0.8, 1.2</li>
            <li>
              全部掛ける：<M>{'1.2 \\times 1.1 \\times 0.8 \\times 1.2 = 1.2672'}</M>（= 253.44 ÷ 200。4年で1.2672倍）
            </li>
            <li>
              4乗根をとる：<M>{'\\sqrt[4]{1.2672} = \\sqrt{\\sqrt{1.2672}} \\approx \\sqrt{1.1257} \\approx 1.0610'}</M>
            </li>
            <li>1 を引く：平均成長率 ≈ <strong>+6.1%</strong></li>
          </Steps>
          <p>
            成長率をふつうに平均すると <M>{'(20 + 10 - 20 + 20) \\div 4 = 7.5'}</M>% で、実際より大きく出てしまいます。
            確かめると <M>{'200 \\times 1.061^4 \\approx 253.4'}</M> で、幾何平均のほうが実際の売上に合います。
          </p>
        </Example>
        <MathNote title="電卓でルートをとる工夫">
          <p>
            統計検定のCBT試験で使えるのは、四則演算・百分率・平方根（√）の計算ができる一般電卓または事務用電卓です
            （<a href="https://www.toukei-kentei.jp/info/other_grades_apply/" target="_blank" rel="noreferrer">統計検定 準1級〜4級試験要項</a>、2026年11月19日参照）。
            √キーはあっても「4乗根」「3乗根」のキーはありません。
          </p>
          <ul>
            <li>
              <strong>2乗根</strong>：√ を1回。<strong>4乗根</strong>：√ を2回（<M>{'\\sqrt[4]{a} = \\sqrt{\\sqrt{a}}'}</M>）。<strong>8乗根</strong>：√ を3回。
            </li>
            <li>
              <strong>3乗根など</strong>：√ ではとれないので、選択肢の値を3回掛けて元の数に近いものを選ぶ。たとえば <M>{'\\sqrt[3]{1.188}'}</M> なら、
              <M>{'1.059^3 \\approx 1.188'}</M> なので約1.059。
            </li>
          </ul>
        </MathNote>
      </Section>

      <Section title="指数化：基準の年を100にそろえる">
        <p>
          大型店（売上 500万円台）と小さな店（売上 40万円台）の伸び方を比べたいとします。そのままグラフにすると、小さな店の線はほぼ平らに見えます。
          そこで、<strong>基準時点</strong>（ここでは基準の年）の値を100として、ほかの年を「基準の何倍か × 100」に直します。これが<strong>指数化</strong>です。
        </p>
        <p>
          基準時点の値を <M>{'x_0'}</M>、時点 <M>{'t'}</M> の値を <M>{'x_t'}</M> とすると、時点 <M>{'t'}</M> の指数 <M>{'I_t'}</M> は次の式です。
        </p>
        <MathBlock caption="指数：基準時点と比べて何倍かを、100を基準に表す">{'I_t = \\frac{x_t}{x_0} \\times 100'}</MathBlock>
        <Figure caption="「指数」に切り替えると、規模のちがう2店の伸び方を同じものさしで比べられる。基準年を変えると、その年が100になる">
          <IndexChart years={YEARS} a={[500, 550, 605, 560, 620]} b={[40, 48, 54, 60, 66]} aLabel="大型店" bLabel="小さな店" />
        </Figure>
        <p>
          2020年を基準にすると、2024年は大型店 <M>{'620 \\div 500 \\times 100 = 124'}</M>、小さな店 <M>{'66 \\div 40 \\times 100 = 165'}</M>。
          金額では大型店のほうがずっと大きく増えていますが、<strong>伸び率</strong>は小さな店のほうが大きいことがわかります。
          消費者物価指数のような公的な統計も、ある年を100とした指数で発表されています。
        </p>
        <Example title="基準時点を変える（基準の取り換え）">
          <p>
            2020年 = 100 の指数で、2022年が120、2024年が150だったとします。2022年 = 100 に直すには、すべての指数を120で割って100を掛けます。
            2024年は <M>{'150 \\div 120 \\times 100 = 125'}</M>。元の金額がわからなくても、指数どうしの割り算で計算できます。
          </p>
        </Example>
      </Section>

      <Section title="よくある勘違い">
        <Pitfall>
          <ul>
            <li>
              成長率をふつうに平均する → 平均成長率は<strong>幾何平均</strong>。算術平均は、幾何平均と等しいかそれより大きく出ます。
            </li>
            <li>+10% のあと −10% で元に戻る → <M>{'1.1 \\times 0.9 = 0.99'}</M> で、1%減っています。</li>
            <li>
              幾何平均を「成長率そのもの」（0.2, 0.1, −0.2…）でとる → マイナスが入ると計算できません。<strong>「何倍」（1.2, 1.1, 0.8…）</strong>で掛け算します。
            </li>
            <li>
              指数の差を「%」と読む → 指数が120から150に上がったのは「30ポイント上昇」で、伸び率は <M>{'150 \\div 120 - 1 = 25'}</M>%。
            </li>
          </ul>
        </Pitfall>
      </Section>

      <Section title="統計検定での出方">
        <ExamTip>
          <ul>
            <li>数年分の成長率（または値）が表で与えられ、平均成長率を幾何平均で求める問題。√を2回押す計算や、選択肢を3乗して確かめる計算が多い。</li>
            <li>「最初と最後の値」だけから、n 年間の平均成長率 <M>{'\\sqrt[n]{x_n / x_0} - 1'}</M>（<M>{'x_0'}</M> が最初、<M>{'x_n'}</M> が最後の値） を求める問題。</li>
            <li>基準年=100 の指数の表やグラフを読み、別の年を基準にした値や、ある期間の伸び率を求める問題。</li>
          </ul>
        </ExamTip>
      </Section>
    </>
  )
}
