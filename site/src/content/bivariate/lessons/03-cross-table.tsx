export const meta: LessonMeta = {
  id: 'bivariate-cross-table',
  chapter: 'bivariate',
  order: 3,
  title: '度数表とクロス集計表',
  summary: '「年代」と「朝ごはんを食べるか」のような、数ではない2つの変数の関係を表にまとめて読む方法です。',
  minutes: 25,
  keywords: ['度数表', '2元クロス表', '行パーセント', '列パーセント'],
}

const ROWS = ['20代', '40代', '60代']
const COLS = ['毎日食べる', '食べない日がある']
const COUNTS = [
  [60, 40],
  [90, 60],
  [120, 30],
]

export default function Lesson() {
  return (
    <>
      <Point>
        <p>
          「年代」×「朝ごはん」のような2つの質的変数（数ではなくカテゴリーで表す変数。<Link to="/lessons/descriptive-data-types">データの種類</Link>）の関係は、<strong>クロス集計表</strong>にまとめます。
          関係を読むときは度数をそのまま比べず、<strong>割合（行パーセント・列パーセント）</strong>にして比べます。
          関係がなければ、どのグループでも割合がそろいます。
        </p>
      </Point>

      <Section title="度数表：1つの変数を数える">
        <p>
          400人に「朝ごはんを毎日食べますか」と聞きました（架空の調査）。答えごとに人数を数えた表が<strong>度数表</strong>です。
          全体に占める割合（<strong>相対度数</strong>）もいっしょに書くと読みやすくなります。
        </p>
        <DataTable
          head={['答え', '度数（人）', '相対度数']}
          rows={[
            ['毎日食べる', '270', '67.5%'],
            ['食べない日がある', '130', '32.5%'],
            [<strong key="t">合計</strong>, '400', '100%'],
          ]}
          caption="朝ごはんの度数表"
        />
      </Section>

      <Section title="クロス集計表：2つの変数を同時に数える">
        <p>
          同じ400人を「年代」でも分けて、2つの変数の組み合わせごとに数えたのが<strong>クロス集計表</strong>（<strong>2元クロス表</strong>、分割表）です。
        </p>
        <DataTable
          head={['年代', '毎日食べる', '食べない日がある', '合計']}
          rows={[
            ['20代', '60', '40', '100'],
            ['40代', '90', '60', '150'],
            ['60代', '120', '30', '150'],
            [<strong key="t">合計</strong>, '270', '130', '400'],
          ]}
          caption="年代 × 朝ごはん のクロス集計表（人）"
        />
        <p>
          いちばん右の列といちばん下の行の「合計」を<strong>周辺度数</strong>といいます。下の行の合計（270, 130）は、上の度数表と同じです。
        </p>
        <p>
          では「40代は20代より朝ごはんを毎日食べる人が多い」といえるでしょうか。40代の「毎日食べる」は90人、20代は60人ですが、40代はそもそも人数が多い（150人と100人）ので、人数のままでは比べられません。そこで割合にします。
        </p>
      </Section>

      <Section title="行パーセントと列パーセント">
        <p>割合にする方法は2つあり、<strong>何で割るか</strong>が違います。</p>
        <Compare>
          <Card title="行パーセント：行の合計で割る">
            <DataTable
              head={['年代', '毎日', 'ない日あり', '合計']}
              rows={[
                ['20代', '60%', '40%', '100%'],
                ['40代', '60%', '40%', '100%'],
                ['60代', '80%', '20%', '100%'],
              ]}
            />
            <p className="small">「20代のうち、毎日食べる人は何％？」に答える。年代どうしを比べたいときに使う。</p>
          </Card>
          <Card title="列パーセント：列の合計で割る">
            <DataTable
              head={['年代', '毎日', 'ない日あり']}
              rows={[
                ['20代', '22.2%', '30.8%'],
                ['40代', '33.3%', '46.2%'],
                ['60代', '44.4%', '23.1%'],
                ['合計', '100%', '100%'],
              ]}
            />
            <p className="small">「毎日食べる人のうち、20代は何％？」に答える。答えのグループの中身（年代の構成）を見たいときに使う。</p>
          </Card>
        </Compare>
        <p>
          行パーセントを見ると、20代と40代は60%、60代は80%が毎日食べています。年代によって割合が違うので、<strong>年代と朝ごはんには関連がある</strong>といえそうです。
        </p>
        <Figure caption="帯グラフ（積み上げ100%棒グラフ）。見るところは「色の境目の位置が帯ごとにそろっているか」。ずれていれば関連がある。ボタンで行パーセントと列パーセントを切りかえられ、「関連の強さ」を0にすると、どの帯も「全体」と同じ区切りになる">
          <CrossTableExplorer rowLabels={ROWS} colLabels={COLS} counts={COUNTS} rowTitle="年代" />
        </Figure>
      </Section>

      <Section title="関連がない ＝ 割合がそろう">
        <Intuition title="関連がないとき、表はどうなる？">
          <p>
            もし年代と朝ごはんに関連がなければ、どの年代でも「毎日食べる」割合は全体と同じ 67.5% になるはずです。
            20代は100人なので <strong>100 × 0.675 = 67.5人</strong>、40代と60代は150人なので <strong>150 × 0.675 = 101.25人</strong>が「毎日食べる」になります。
          </p>
        </Intuition>
        <MathBlock caption="関連がないときに期待される度数：（その行の合計）×（その列の合計）÷（総数）">{'E_{ij} = \\frac{R_i \\times C_j}{N}'}</MathBlock>
        <p>
          <M>{'E_{ij}'}</M> は「i 行目・j 列目のマス」の期待される度数（期待度数）、<M>{'R_i'}</M> は i 行目の合計、<M>{'C_j'}</M> は j 列目の合計、<M>{'N'}</M> は総数です。
          たとえば「40代（2行目）× 毎日食べる（1列目）」なら <M>{'E_{21} = 150 \\times 270 \\div 400 = 101.25'}</M>。上の図のスライダーを0にしたときの表がこれです。
          実際の度数がこの「関連がないときの度数」からどれくらいずれているかを1つの数にまとめて、関連があるといえるかを調べるのが<strong>独立性の検定</strong>（カイ二乗検定）です。
          くわしくは<Link to="/lessons/testing-chi2">「適合度検定と独立性の検定」のレッスン</Link>で扱います。
        </p>
      </Section>

      <Section title="ちょっと寄り道：シンプソンのパラドックス">
        <p>
          ある病気に対する治療法 A と B の結果を、軽症と重症に分けて集計しました（架空のデータ）。
        </p>
        <DataTable
          head={['', '治療法 A', '治療法 B']}
          rows={[
            ['軽症', '19 / 20人 回復（95%）', '72 / 80人 回復（90%）'],
            ['重症', '48 / 80人 回復（60%）', '10 / 20人 回復（50%）'],
            [<strong key="t">合計</strong>, '67 / 100人 回復（67%）', '82 / 100人 回復（82%）'],
          ]}
          caption="重症度別の回復率"
        />
        <Figure caption="青が A、オレンジが B。軽症の組・重症の組ではどちらも青の棒が高いのに、合計の組だけオレンジの棒が高くなる">
          <Plot x={[0, 9]} y={[0, 110]} height={260} yLabel="回復率（%）" xTicks={[1.5, 4.5, 7.5]} xTickFormat={(v) => (v === 1.5 ? '軽症' : v === 4.5 ? '重症' : '合計')}>
            <Bars data={[{ x: 1, y: 95 }, { x: 4, y: 60 }, { x: 7, y: 67 }]} color="c1" labels={(v) => `${v}%`} />
            <Bars data={[{ x: 2, y: 90 }, { x: 5, y: 50 }, { x: 8, y: 82 }]} color="c2" labels={(v) => `${v}%`} />
          </Plot>
          <Legend
            items={[
              { color: 'c1', label: '治療法 A' },
              { color: 'c2', label: '治療法 B' },
            ]}
          />
        </Figure>
        <p>
          A は重症の人に多く使われ（100人中80人）、B は軽症の人に多く使われています（100人中80人）。重症の人は回復しにくいので、合計すると A の成績が悪く見えます。
          このように、グループに分けたときと合計したときで結論が逆になる現象を<strong>シンプソンのパラドックス</strong>といいます。前のレッスンの「層別で関係が逆転する」と同じしくみです。
        </p>
      </Section>

      <Section title="よくある勘違い">
        <Pitfall>
          <ul>
            <li>度数（人数）のまま比べる → グループの人数が違うときは、必ず割合にしてから比べます。</li>
            <li>
              行パーセントと列パーセントを取り違える → 「<strong>〜のうち</strong>、…は何％」の「〜」が割る数（分母）です。
              「20代のうち毎日食べる人」は 60 ÷ 100、「毎日食べる人のうち20代」は 60 ÷ 270 です。
            </li>
            <li>関連があるから因果関係がある → クロス集計表でも、第3の変数（たとえば重症度）を考える必要があります。</li>
          </ul>
        </Pitfall>
        <Example title="どちらのパーセントを使う？">
          <p>
            「年代によって朝ごはんの習慣が違うか」を知りたいなら、年代（行）ごとに割合を出す<strong>行パーセント</strong>。
            「朝ごはんを食べない人はどの年代に多いか」を知りたいなら、答え（列）ごとに割合を出す<strong>列パーセント</strong>です。
            ふつうは「原因の側・グループの側」で割ると、比べたいことがはっきりします。
          </p>
        </Example>
      </Section>

      <Section title="統計検定での出方">
        <ExamTip>
          <ul>
            <li>クロス集計表から、行パーセントや列パーセントを計算させる問題。「〜のうち」が何かを読み取るのがポイント。</li>
            <li>帯グラフ（積み上げ棒グラフ）とクロス集計表の対応を問う問題。</li>
            <li>関連がないときに期待される度数を計算させる問題（独立性の検定の準備として）。</li>
            <li>
              クロス集計表を示して「正しい記述をすべて選べ」（I・II・III の組み合わせ）の形で問う問題。記述ごとに「分母は何か（〜のうち）」を確かめてから計算します。
            </li>
          </ul>
        </ExamTip>
      </Section>
    </>
  )
}
